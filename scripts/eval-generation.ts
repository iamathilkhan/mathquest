/**
 * scripts/eval-generation.ts
 *
 * Produces docs/EVAL.md with REAL, script-computed statistics — no fabricated
 * numbers (project rule: any statistic in docs must be produced by a script). It
 * re-runs the server-side verifier over every committed seed question and seed
 * lesson and reports counts, per-tier inventory, and a reject-reason histogram.
 *
 * Scope and honesty:
 *  - Measured here: SEED-BANK verification. Deterministic, offline, no LLM model
 *    required. The verifier is the same `verifyQuestion` / `verifyLesson` the API
 *    route handlers use, so this reports exactly how much committed content is
 *    mathematically sound.
 *  - NOT measured here: live LLM accept-rate, reject reasons, and latency for the
 *    /api/lesson and /api/questions endpoints. Those require GEMINI_API_KEY and a
 *    network call, and are intentionally out of scope for this offline report.
 *
 * Run: npm run eval
 */
import fs from "node:fs";
import path from "node:path";

import { ALL_SUBSKILLS } from "@/data/curriculum";
import { LessonSchema, RawQuestionSchema } from "@/lib/schemas";
import { verifyLesson } from "@/lib/verify/lesson";
import { verifyQuestion } from "@/lib/verify/question";

type Tier = "easy" | "medium" | "hard";

interface SubSkillRow {
  realmId: string;
  subSkillId: string;
  tiers: Record<Tier, number>;
  lessonOk: boolean;
}

const ROOT = process.cwd();
const readJson = (file: string): unknown => JSON.parse(fs.readFileSync(file, "utf8"));

function main(): void {
  fs.mkdirSync(path.join(ROOT, "docs"), { recursive: true });

  const rows: SubSkillRow[] = [];
  const rejectReasons: Record<string, number> = {};
  const tallyReject = (reason: string) => {
    rejectReasons[reason] = (rejectReasons[reason] ?? 0) + 1;
  };

  let totalQuestions = 0;
  let verifiedQuestions = 0;
  let totalLessons = 0;
  let verifiedLessons = 0;
  const tierTotals: Record<Tier, number> = { easy: 0, medium: 0, hard: 0 };

  for (const skill of ALL_SUBSKILLS) {
    const qPath = path.join(ROOT, "data/seed-questions", `${skill.realmId}__${skill.id}.json`);
    const lPath = path.join(ROOT, "data/lessons", `${skill.realmId}__${skill.id}.json`);
    const tiers: Record<Tier, number> = { easy: 0, medium: 0, hard: 0 };
    let lessonOk = false;

    if (fs.existsSync(qPath)) {
      const payload = readJson(qPath) as { items?: unknown[] };
      for (const item of payload.items ?? []) {
        totalQuestions += 1;
        const parsed = RawQuestionSchema.safeParse(item);
        if (!parsed.success) {
          tallyReject("question_schema_invalid");
          continue;
        }
        const verified = verifyQuestion(parsed.data);
        if (verified.ok) {
          verifiedQuestions += 1;
          tiers[verified.q.tier] += 1;
          tierTotals[verified.q.tier] += 1;
        } else {
          tallyReject(verified.reason);
        }
      }
    }

    if (fs.existsSync(lPath)) {
      const payload = readJson(lPath) as Record<string, unknown> & { lesson?: unknown };
      totalLessons += 1;
      const lesson = LessonSchema.safeParse(payload.lesson ?? payload);
      if (!lesson.success) {
        tallyReject("lesson_schema_invalid");
      } else {
        const checked = verifyLesson(lesson.data);
        lessonOk = checked.ok;
        if (checked.ok) verifiedLessons += 1;
        else tallyReject(`lesson:${checked.reason}`);
      }
    }

    rows.push({ realmId: skill.realmId, subSkillId: skill.id, tiers, lessonOk });
  }

  const questionPassRate = totalQuestions ? ((verifiedQuestions / totalQuestions) * 100).toFixed(1) : "0.0";
  const lessonPassRate = totalLessons ? ((verifiedLessons / totalLessons) * 100).toFixed(1) : "0.0";
  const now = new Date().toISOString();

  const lines: string[] = [
    "# MathQuest Evaluation Report",
    "",
    `Generated by \`scripts/eval-generation.ts\` on ${now}.`,
    "",
    "Every number below is computed by re-running the server-side verifier over the",
    "committed seed bank. No figure is hand-written (project rule: any statistic in",
    "docs must be produced by a script).",
    "",
    "## Scope",
    "",
    "- **Measured:** seed-bank verification — deterministic, offline, no LLM model",
    "  required. Each committed seed question and seed lesson is re-verified with the",
    "  same `verifyQuestion` / `verifyLesson` the API route handlers use.",
    "- **Not measured here:** live LLM accept-rate, reject-reason distribution, and",
    "  latency for `POST /api/lesson` and `POST /api/questions`. Those require",
    "  `GEMINI_API_KEY` and a network call and are intentionally out of scope for this",
    "  offline report (see the last section for how to add them).",
    "",
    "## Headline",
    "",
    "| Metric | Value |",
    "| --- | --- |",
    `| Sub-skills inspected | ${ALL_SUBSKILLS.length} |`,
    `| Seed questions re-verified | ${totalQuestions} |`,
    `| Seed questions passing verifier | ${verifiedQuestions} (${questionPassRate}%) |`,
    `| Seed lessons re-verified | ${totalLessons} |`,
    `| Seed lessons passing verifier | ${verifiedLessons} (${lessonPassRate}%) |`,
    `| Questions per tier (easy / medium / hard) | ${tierTotals.easy} / ${tierTotals.medium} / ${tierTotals.hard} |`,
    "",
    "## Reject-reason histogram",
    "",
  ];

  const rejectKeys = Object.keys(rejectReasons);
  if (rejectKeys.length === 0) {
    lines.push("No rejects — every seed item passes the verifier.");
  } else {
    lines.push("| Reason | Count |", "| --- | --- |");
    for (const [reason, count] of Object.entries(rejectReasons)) lines.push(`| ${reason} | ${count} |`);
  }

  lines.push(
    "",
    "## Per sub-skill",
    "",
    "| Realm | Sub-skill | Easy | Medium | Hard | Lesson verified |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.realmId} | ${r.subSkillId} | ${r.tiers.easy} | ${r.tiers.medium} | ${r.tiers.hard} | ${r.lessonOk ? "yes" : "no"} |`),
    "",
    "## Adding live-LLM measurements",
    "",
    "1. Set `GEMINI_API_KEY` and `GEMINI_MODEL_PRIMARY` (optionally",
    "   `GEMINI_MODEL_FALLBACK`) in `.env.local`.",
    "2. Extend this script (or add `scripts/eval-live.ts`) to call `/api/lesson` and",
    "   `/api/questions` for each sub-skill, recording the returned `source`",
    "   distribution (`live` / `cache` / `mixed` / `seed`), the verifier `rejectReasons`,",
    "   and request latency. Append a table here with the model name and date.",
    "",
  );

  const output = path.join(ROOT, "docs", "EVAL.md");
  fs.writeFileSync(output, lines.join("\n"));
  console.log(`Wrote ${output}`);
  console.log(`Questions: ${verifiedQuestions}/${totalQuestions} verified (${questionPassRate}%) — lessons: ${verifiedLessons}/${totalLessons} (${lessonPassRate}%)`);
}

main();
